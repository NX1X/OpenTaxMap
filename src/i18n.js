export function makeT(lang) {
  const table = STRINGS[lang] || STRINGS.he
  return (key, vars) => {
    let s = table[key]
    if (s === undefined) s = STRINGS.he[key]
    if (typeof s === 'string' && vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v)
    }
    return s
  }
}
